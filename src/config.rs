use bevy::prelude::*;

/// 模拟世界的全局可调参数。
///
/// 所有数值都在这里集中管理，修改后保存并重新运行即可生效。
/// 这些参数共同决定了生态系统的动态平衡：食物、生物、捕食者之间的节奏。
/// 调整时建议一次只改 1～2 个参数，观察效果后再继续，因为参数之间会相互影响。
#[derive(Resource, Clone)]
pub struct SimConfig {
    // =========================================================================
    // 世界与初始规模
    // =========================================================================

    /// 世界半宽与半高。
    ///
    /// 实际世界范围是 `[-world_half_size.x, world_half_size.x]`
    /// 与 `[-world_half_size.y, world_half_size.y]` 的矩形区域。
    /// 所有生物、食物、捕食者都会在这个范围内活动，碰到边界会反弹。
    ///
    /// 默认值 1200 × 800 意味着实际世界大小为 2400 × 1600。
    pub world_half_size: Vec2,

    /// 初始普通生物数量。
    ///
    /// 启动时会在世界范围内随机位置生成这么多生物，并随机分配种族、
    /// 初始能量（30～80）、寿命（1500～2500 tick）和繁殖冷却。
    ///
    /// 注意：这个值可能高于环境长期承载力，开局后种群会自然回落到稳态。
    /// 生物数量直接影响首帧压力和每帧渲染开销，过多会导致启动卡顿。
    /// 默认值 5000 是在视觉效果和性能之间的折中。
    pub creature_count: usize,

    /// 初始食物粒子数量。
    ///
    /// 启动时会在世界范围内随机位置生成这么多食物。
    /// 食物会被生物吃掉，也会按 `food_spawn_per_tick` 持续补充。
    ///
    /// 这个值只影响开局瞬间的食物密度，不影响长期投放速率。
    pub food_count: usize,

    /// 初始捕食者数量。
    ///
    /// 启动时会在世界范围内随机位置生成这么多捕食者。
    /// 捕食者会追击并吃掉普通生物，是食物链的顶层。
    ///
    /// 捕食者太少会导致几乎看不到捕食效果；太多会导致生物被快速吃光，
    /// 然后捕食者因饥饿大量死亡，形成剧烈震荡。默认值 20 是一个相对温和的起点。
    pub predator_count: usize,

    // =========================================================================
    // 时间步长
    // =========================================================================

    /// 模拟逻辑更新频率，单位：tick / 秒。
    ///
    /// 所有与生物行为、代谢、繁殖、食物投放、捕食相关的系统都在 FixedUpdate 中运行，
    /// 因此这个值直接决定模拟节奏。
    ///
    /// - 值越大，模拟更新越快，生物/捕食者动作越灵敏
    /// - 值越大，每帧计算量也越大，可能降低帧率
    ///
    /// 例如 30.0 表示每秒 30 个 tick，每个 tick 约 33.3 毫秒。
    /// 注意：修改此值会影响所有“每 tick”参数的实际时间含义。
    pub ticks_per_second: f32,

    // =========================================================================
    // 普通生物参数
    // =========================================================================

    /// 普通生物每 tick 的基础代谢消耗。
    ///
    /// 只要活着，每个生物每 tick 都会扣除这么多能量。
    ///
    /// - 调大：生物饿死更快，种群压力增大，稳态种群数量下降
    /// - 调小：生物更容易存活，种群更容易爆炸
    ///
    /// 默认值 0.12 配合能量上限 100，意味着完全不进食约能活 833 tick（约 27 秒）。
    pub metabolism_rate: f32,

    /// 普通生物吃掉一份食物后恢复的能量。
    ///
    /// 生物进入食物附近（半径 8）时会自动吃掉它，并将当前能量增加该值，
    /// 但不超过能量上限 100。
    ///
    /// - 调大：每份食物更“顶饱”，生态系统能支撑更多生物
    /// - 调小：食物更稀缺，种群更容易崩溃
    ///
    /// 默认值 25 意味着吃 4 份食物就能从 0 恢复到满能量。
    pub food_energy_value: f32,

    /// 普通生物的饥饿阈值，以能量百分比表示。
    ///
    /// 当 `current_energy / max_energy` 低于这个值时，生物会主动寻找食物，
    /// 并且会与同族分享食物位置信息。
    ///
    /// - 调低（如 0.3）：生物更“佛系”，很少主动觅食和通讯
    /// - 调高（如 0.8）：生物很积极，通讯更频繁，但可能更拥挤在食物附近
    ///
    /// 默认值 0.55 表示能量低于 55% 时进入饥饿状态。
    pub hungry_threshold: f32,

    /// 普通生物繁殖所需的最低能量。
    ///
    /// 只有当前能量大于等于这个值的生物才可能繁殖。
    /// 繁殖时还会扣除 `reproduction_cost` 能量。
    ///
    /// - 调低：更多生物能繁殖，种群增长更快
    /// - 调高：只有“富裕”生物能繁殖，种群增长更慢但更稳定
    ///
    /// 默认值 75 意味着生物需要恢复到较高能量水平才能繁殖。
    pub reproduction_threshold: f32,

    /// 普通生物繁殖时从父代扣除的能量。
    ///
    /// 后代实际获得的初始能量是 `reproduction_cost * 0.5`，
    /// 另一半能量从系统中“消失”，作为繁殖 overhead。
    /// 父代能量会减少 `reproduction_cost`。
    ///
    /// - 调大：每次繁殖代价高，种群增长慢，但 overhead 也更大，更耗能
    /// - 调小：繁殖更容易，种群增长快
    ///
    /// 默认值 35 意味着后代出生时有 17.5 能量，父代损失 35 能量。
    pub reproduction_cost: f32,

    /// 普通生物繁殖冷却时间，单位：tick。
    ///
    /// 生物成功繁殖后，需要等待这么多 tick 才能再次繁殖。
    /// 用于防止种群在食物充足时瞬间爆炸。
    ///
    /// - 调小：繁殖更频繁，种群增长更快
    /// - 调大：繁殖更稀疏，种群更稳定
    ///
    /// 默认值 20 tick 约等于 0.67 秒（按 30 tick/秒计算）。
    pub reproduction_cooldown: f32,

    /// 普通生物最大移动速度，单位：世界单位 / tick。
    ///
    /// 限制了生物每 tick 最多能移动多远。
    /// 生物的实际速度还会受到转向力度和游荡的影响。
    ///
    /// - 调大：生物移动更快，更容易找到食物，但也会更快耗尽能量区域
    /// - 调小：生物移动慢，觅食效率低，更容易饿死
    ///
    /// 默认值 6.0。
    pub max_speed: f32,

    /// 普通生物觅食时的转向力度。
    ///
    /// 数值越大，生物朝向食物或接收到的食物方向转向越激进，
    /// 转弯半径越小。
    ///
    /// - 调大：生物更“果断”，直奔食物
    /// - 调小：生物转向更平缓，可能绕路
    ///
    /// 默认值 0.35。
    pub seek_strength: f32,

    /// 普通生物漫游时的随机转向力度。
    ///
    /// 即使没有目标，生物也会以这个强度随机改变方向，避免全部静止或扎堆。
    ///
    /// - 调大：生物更“躁动”，探索范围更大
    /// - 调小：生物更“懒散”，容易原地打转
    ///
    /// 默认值 0.12。
    pub wander_strength: f32,

    /// 普通生物感知食物的半径，单位：世界单位。
    ///
    /// 饥饿时生物只会在这个范围内寻找食物。
    ///
    /// - 调大：生物“看得更远”，更容易找到食物
    /// - 调小：生物更依赖同族通讯或随机游荡
    ///
    /// 这个值还会影响空间网格的单元格大小（取最大半径的 1.5 倍）。
    /// 默认值 70.0。
    pub perception_radius: f32,

    /// 普通生物同族通讯半径，单位：世界单位。
    ///
    /// 饥饿且发现食物的生物会把这个信息告诉同族，但只在这个半径内的同族能收到。
    ///
    /// - 调大：信息传播范围更广，群体觅食更明显
    /// - 调小：信息更局部，群体效应减弱
    ///
    /// 这个值也会影响空间网格的单元格大小。
    /// 默认值 50.0。
    pub communication_radius: f32,

    /// 普通生物察觉捕食者并逃跑的半径，单位：世界单位。
    ///
    /// 当生物在这个范围内发现捕食者时，会朝反方向逃跑。
    /// 这是让“恐慌波”这种涌现现象直观可见的关键参数。
    ///
    /// - 调大：生物更早发现危险，更容易形成大面积逃跑潮
    /// - 调小：捕食者更容易突袭成功，逃跑效果不明显
    ///
    /// 这个值也会影响空间网格的单元格大小。
    /// 默认值 90.0。
    pub predator_flee_radius: f32,

    /// 普通生物逃跑时的转向力度。
    ///
    /// 数值越大，生物逃离捕食者时转向越激进。
    ///
    /// - 调大：逃跑更果断，恐慌波更明显
    /// - 调小：逃跑更迟缓，捕食者更容易追上
    ///
    /// 默认值 0.8。
    pub flee_strength: f32,

    /// 普通生物的物种数量。
    ///
    /// 每个物种拥有独立的颜色，并且只在同种之间通讯。
    /// 颜色循环为：红 → 蓝 → 黄 → 绿 → 红……
    ///
    /// - 调大：更多颜色/派系，信息隔离更明显
    /// - 调小：信息更容易在全局传播（但仍是同族内）
    ///
    /// 默认值 3。
    pub species_count: u8,

    // =========================================================================
    // 食物投放参数
    // =========================================================================

    /// 每个 tick 投放的食物粒子数量。
    ///
    /// 结合 `ticks_per_second`，可以算出每秒投放总量。
    /// 例如 40 × 30 = 每秒 1200 个食物。
    ///
    /// 这个值决定了生态系统的长期食物供给能力，直接影响稳态种群数量。
    ///
    /// - 调大：食物更充足，能支撑更多生物
    /// - 调小：食物更稀缺，种群数量下降
    ///
    /// 默认值 40。
    pub food_spawn_per_tick: usize,

    // =========================================================================
    // 捕食者参数
    // =========================================================================

    /// 捕食者最大移动速度，单位：世界单位 / tick。
    ///
    /// 捕食者的实际速度还会受到转向力度和游荡的影响。
    ///
    /// - 必须略高于普通生物的 `max_speed`，否则永远追不上猎物
    /// - 调得过高：捕食者无敌，生物很快灭绝
    /// - 调得过低：捕食者追不上猎物，会全部饿死
    ///
    /// 默认值 7.5（普通生物为 6.0）。
    pub predator_speed: f32,

    /// 捕食者探测普通生物的半径，单位：世界单位。
    ///
    /// 捕食者只在这个范围内寻找最近的猎物并发起追击。
    ///
    /// - 调大：捕食者更容易发现猎物，捕食效率更高
    /// - 调小：捕食者更“近视”，猎物更容易逃脱
    ///
    /// 这个值也会影响空间网格的单元格大小。
    /// 默认值 120.0。
    pub predator_perception_radius: f32,

    /// 捕食者每 tick 的基础代谢消耗。
    ///
    /// 只要活着，每个捕食者每 tick 都会扣除这么多能量。
    ///
    /// - 调大：捕食者饿死更快，对猎物种群压力减小
    /// - 调小：捕食者更容易存活，可能过度捕猎
    ///
    /// 默认值 0.25 配合能量上限 100，意味着完全不进食约能活 400 tick（约 13 秒）。
    pub predator_metabolism_rate: f32,

    /// 捕食者成功吃掉一只普通生物后获得的能量。
    ///
    /// 这是捕食者主要的能量来源。
    /// 获得能量后会受上限 100 限制。
    ///
    /// - 调大：每次捕食收益高，捕食者更容易维持和繁殖
    /// - 调小：捕食者需要更频繁捕食，生存压力更大
    ///
    /// 默认值 60.0。
    pub predator_energy_gain: f32,

    /// 捕食者繁殖所需的最低能量。
    ///
    /// 只有当前能量大于等于这个值的捕食者才可能繁殖。
    /// 繁殖时还会扣除 `reproduction_cost` 能量（与普通生物共用同一参数）。
    ///
    /// - 调低：捕食者更容易繁殖，种群增长快
    /// - 调高：捕食者繁殖更困难，种群更稳定
    ///
    /// 默认值 90.0。
    pub predator_reproduction_threshold: f32,
}

impl Default for SimConfig {
    fn default() -> Self {
        Self {
            // 世界尺寸：实际范围 2400 × 1600
            world_half_size: Vec2::new(1200.0, 800.0),

            // 初始种群规模
            // 10000 在首帧会给 CPU/GPU 带来较大压力，5000 仍能保持涌现效果且更流畅
            creature_count: 5_000,
            food_count: 1_500,
            predator_count: 20,

            // 逻辑更新频率：每秒 30 tick
            ticks_per_second: 30.0,

            // 普通生物能量相关
            metabolism_rate: 0.12,
            food_energy_value: 25.0,
            hungry_threshold: 0.55,

            // 普通生物繁殖相关
            reproduction_threshold: 75.0,
            reproduction_cost: 35.0,
            reproduction_cooldown: 20.0,

            // 普通生物移动与行为
            max_speed: 6.0,
            seek_strength: 0.35,
            wander_strength: 0.12,
            perception_radius: 70.0,
            communication_radius: 50.0,
            predator_flee_radius: 90.0,
            flee_strength: 0.8,

            // 普通生物物种数量
            species_count: 3,

            // 食物投放：每 tick 40 个，每秒 1200 个
            food_spawn_per_tick: 40,

            // 捕食者相关
            predator_speed: 7.5,
            predator_perception_radius: 120.0,
            predator_metabolism_rate: 1.0,
            predator_energy_gain: 60.0,
            predator_reproduction_threshold: 90.0,
        }
    }
}

impl SimConfig {
    /// 空间网格的单元格大小。
    ///
    /// 空间网格用于加速邻居查询（找食物、找同族、找猎物等）。
    /// 单元格大小必须至少不小于最大的交互半径，
    /// 这样任意两个可能发生交互的实体一定位于同一个或相邻的单元格中，
    /// 从而保证查询结果正确。
    ///
    /// 这里取普通生物感知半径、通讯半径和捕食者感知半径三者的最大值，再乘以 1.5，
    /// 兼顾查询效率与正确性。
    pub fn cell_size(&self) -> f32 {
        self.perception_radius
            .max(self.communication_radius)
            .max(self.predator_perception_radius)
            .max(self.predator_flee_radius)
            * 1.5
    }
}
